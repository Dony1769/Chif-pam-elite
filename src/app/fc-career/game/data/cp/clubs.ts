/** Masse salariale hebdomadaire (€) : exponentielle de la réputation, pondérée par la richesse de la ligue. */
export function cpWages(rep: number, wealth: number): number {
  return Math.round((4_500_000 * Math.exp((rep - 95) * 0.075) * wealth) / 1000) * 1000;
}

export const CP_CLUBS: (Club & { stadiumCapacity: number })[] = CP_LEAGUES.flatMap(l =>
  ROWS[l.id].map(([id, name, shortName, primary, secondary, reputation, philosophy, academyLevel, cap]) => {
    const wagesBudget = cpWages(reputation, l.wealth);
    return {
      id, name: `CP ${name}`, shortName, countryId: l.countryId, leagueId: l.id, tier: l.tier,
      colors: { primary, secondary }, wagesBudget, transferBudget: Math.round((wagesBudget * 30) / 100_000) * 100_000,
      reputation, academyLevel, philosophy, stadiumCapacity: cap,
    };
  }),
);

export const CP_CLUB_IDS = new Set(CP_CLUBS.map(c => c.id));
